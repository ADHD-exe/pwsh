# Offline test for bootstrap/lib/Json.ps1 (runs on any OS with PowerShell 7).
#   pwsh -NoProfile -File tests/Test-TerminalMerge.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
. (Join-Path $root 'bootstrap/lib/Common.ps1')
. (Join-Path $root 'bootstrap/lib/Json.ps1')

$failures = 0
function Assert { param([bool]$Condition, [string]$Name)
    if ($Condition) { Write-Host "  pass  $Name" -ForegroundColor Green }
    else { Write-Host "  FAIL  $Name" -ForegroundColor Red; $script:failures++ }
}

$template = ConvertTo-PlainJsonObject (Get-Content (Join-Path $root 'settings/settings.json') -Raw)

# A machine file as Windows Terminal generates it: comments, extra profiles, other defaults.
$machineText = @'
{
    // This file was generated by Windows Terminal
    "$help": "https://aka.ms/terminal-documentation",
    "defaultProfile": "{61c54bbd-c2c6-5271-96e7-009a87ff44bf}",
    "copyOnSelect": false,
    "profiles": {
        "defaults": { "opacity": 50, "someMachineOnly": true },
        "list": [
            { "guid": "{61c54bbd-c2c6-5271-96e7-009a87ff44bf}", "name": "Windows PowerShell", "commandline": "powershell.exe" },
            { "guid": "{aaaaaaaa-0000-0000-0000-000000000001}", "name": "Ubuntu", "source": "Windows.Terminal.Wsl" }
        ]
    },
    "schemes": [ { "name": "MachineScheme", "background": "#000000" } ],
    "actions": [],
    "keybindings": [ { "id": "Terminal.CopyToClipboard", "keys": "ctrl+shift+c" } ]
}
'@

$machine = ConvertTo-PlainJsonObject $machineText
$merged  = Merge-TerminalSettings -Machine $machine -Template $template

Write-Host "Terminal settings merge"
Assert ($merged.defaultProfile -eq $template.defaultProfile)                       'template defaultProfile wins'
Assert ($merged.copyOnSelect -eq $template.copyOnSelect)                           'template scalar wins over machine scalar'
Assert ($merged.profiles.defaults.someMachineOnly -eq $true)                       'machine-only default key survives'
Assert ($merged.profiles.defaults.colorScheme -eq $template.profiles.defaults.colorScheme) 'template default colorScheme applied'
Assert (@($merged.profiles.list | Where-Object name -eq 'Ubuntu').Count -eq 1)     'machine-only profile (WSL) kept'
Assert (@($merged.profiles.list | Where-Object name -eq 'Pwsh').Count -eq 1)       'template Pwsh profile added'
Assert ((@($merged.profiles.list | Where-Object name -eq 'Pwsh').commandline) -eq 'pwsh.exe') 'Pwsh profile launches pwsh.exe via PATH (not the MSIX alias)'
Assert (@($merged.schemes | Where-Object name -eq 'MachineScheme').Count -eq 1)    'machine-only scheme kept'
Assert (@($merged.schemes | Where-Object name -eq 'ADHD').Count -eq 1)             'template ADHD scheme added'
Assert (@($merged.keybindings | Where-Object keys -eq 'ctrl+shift+c').Count -eq 1) 'machine-only keybinding kept'
Assert ($merged.keybindings.Count -eq $template.keybindings.Count + 1)             'keybindings: template + 1 machine-only, no duplicates'
Assert ($merged.actions.Count -eq $template.actions.Count)                         'actions merged without duplicates'

$problems = @(Test-TerminalSettings $merged)
Assert ($problems.Count -eq 0) "merged settings validate ($($problems -join '; '))"

$again = Merge-TerminalSettings -Machine $merged -Template $template
Assert (($again | ConvertTo-Json -Depth 32) -eq ($merged | ConvertTo-Json -Depth 32)) 'merge is idempotent (second run changes nothing)'

Assert ($merged.newTabMenu -is [array])                                           'single-element arrays (newTabMenu) stay arrays'
$roundTrip = $merged | ConvertTo-Json -Depth 32 | ConvertFrom-Json
Assert ($null -ne $roundTrip.profiles.list)                                        'result serialises to valid JSON'

if ($failures) { Write-Host "`n$failures failure(s)" -ForegroundColor Red; exit 1 }
Write-Host "`nall passed" -ForegroundColor Green
